pub const INSTANCE_FILE: &str = "instance.json";
pub const SCHEMA_VERSION: u32 = 1;
/// Folders every instance gets on creation.
pub const SUBDIRS: &[&str] = &[
    "mods",
    "config",
    "saves",
    "resourcepacks",
    "shaderpacks",
    "screenshots",
    "logs",
];
const MAX_NAME_LEN: usize = 64;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub enum LoaderKind {
    #[default]
    Vanilla,
    Fabric,
    Quilt,
    LegacyFabric,
    Forge,
    NeoForge,
    Optifine,
}

#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct LoaderSpec {
    pub kind: LoaderKind,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub version: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct Resolution {
    pub width: u32,
    pub height: u32,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct Instance {
    #[serde(default)]
    pub schema_version: u32,
    /// Folder name; authoritative value is the directory, not the file.
    #[serde(default)]
    pub id: String,
    pub name: String,
    /// Preset icon key rendered by the UI (`grass`, `pickaxe`, …).
    #[serde(default = "default_icon")]
    pub icon: String,
    pub mc_version: String,
    #[serde(default)]
    pub loader: LoaderSpec,
    /// Explicit `java` executable; `None` = automatic.
    #[serde(default)]
    pub java_path: Option<String>,
    /// `None` = launcher default.
    #[serde(default)]
    pub memory_mb: Option<u32>,
    /// Extra JVM arguments, space separated (quotes supported).
    #[serde(default)]
    pub jvm_args: String,
    #[serde(default)]
    pub resolution: Option<Resolution>,
    #[serde(default)]
    pub fullscreen: bool,
    #[serde(default)]
    #[ts(type = "number")]
    pub created_at: u64,
    #[serde(default)]
    #[ts(type = "number | null")]
    pub last_played: Option<u64>,
    #[serde(default)]
    #[ts(type = "number")]
    pub play_time_secs: u64,
}

fn default_icon() -> String {
    "grass".into()
}

